def test_make_escaping() -> None:
    assert p.dependencies(
        b"obj\\ name.o: src\\ name.cpp /sdk/a\\#b.h \\\n /sdk/a$$b.h\n"
    ) == ["src name.cpp", "/sdk/a#b.h", "/sdk/a$b.h"]


