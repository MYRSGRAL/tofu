def test_fixed_tool_fd_closed_and_hashed(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    import hashlib
    import os

    sdk = tmp_path / "sdk"
    sdk.mkdir()
    binary = sdk / "compiler"
    binary.write_bytes(b"not executable, fixture only")
    alias = sdk / "fixed-alias"
    alias.symlink_to(binary)
    monkeypatch.setitem(p.PROFILE, "sdk_root", str(sdk))
    monkeypatch.setitem(p.PROFILE, "compiler", str(alias))
    with p.trusted_tool(str(alias)) as (fd, identity):
        assert identity["sha256"] == hashlib.sha256(binary.read_bytes()).hexdigest()
