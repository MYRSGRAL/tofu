@pytest.mark.parametrize("failure", ["cap", "deadline", None])
def test_executor_bounds_and_reaps_without_execution(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch, failure: str | None
) -> None:
    from types import SimpleNamespace

    class Stream:
        def __init__(self, fd: int) -> None:
            self.fd = fd

        def fileno(self) -> int:
            return self.fd

    class Process:
        pid = 123456
        stdout = Stream(100)
        stderr = Stream(101)
        waits = 0

        def __enter__(self):
            return self

        def __exit__(self, *args):
            return False

        def wait(self, timeout: float | None = None) -> int:
            self.waits += 1
            return 0

    class Selector:
        def __init__(self) -> None:
            self.keys = {}

        def __enter__(self):
            return self

        def __exit__(self, *args):
            return False

        def register(self, stream: Stream, events: int, index: int) -> None:
            self.keys[stream.fd] = SimpleNamespace(fileobj=stream, data=index)

        def unregister(self, stream: Stream) -> None:
            del self.keys[stream.fd]

        def get_map(self) -> dict:
            return self.keys

        def select(self, timeout: float) -> list:
            return [(value, 1) for value in list(self.keys.values())]

    child = Process()
    launched = []
    killed = []

    def popen(argv: list[str], **kwargs):
        launched.append(kwargs)
        return child

    monkeypatch.setattr(p.subprocess, "Popen", popen)
    monkeypatch.setattr(p.selectors, "DefaultSelector", Selector)
    monkeypatch.setattr(p.os, "set_blocking", lambda *args: None)
    monkeypatch.setattr(p.os, "killpg", lambda pid, sig: killed.append(pid))
    monkeypatch.setattr(
        p.os, "read", lambda *args: b"xxxx" if failure == "cap" else b""
    )
    monkeypatch.setitem(p.PROFILE, "stream_cap", 3)
    clock = iter([0, 301]) if failure == "deadline" else None
    monkeypatch.setattr(p.time, "monotonic", lambda: next(clock) if clock else 0)
    if failure:
        with pytest.raises(ValueError, match="cap|deadline"):
            p.execute(999, ["fixed-tool"], tmp_path, {})
    else:
        assert p.execute(999, ["fixed-tool"], tmp_path, {}) == (0, b"", b"")
    assert launched[0]["executable"] == "/proc/self/fd/999"
    assert launched[0]["pass_fds"] == (999,)
    assert launched[0]["start_new_session"] is True
    assert "shell" not in launched[0]
    assert killed == [child.pid] and child.waits >= 1
